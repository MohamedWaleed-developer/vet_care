// بنستورد موديل التطعيمات
// لأننا هنستخدم VaccinationModel داخل الملف
import '../../models/vaccination_model.dart';


// الكلاس ده فيه الدوال المساعدة الخاصة بالتواريخ
// بدل ما نكرر نفس كود التواريخ في كل Calculator
class VaccinationDateHelper {

  // ---------------------------------------------------------
  // دالة بتضيف سنة كاملة على تاريخ معين
  // مثال:
  // 20/9/2026
  // تصبح:
  // 20/9/2027
  // ---------------------------------------------------------
  static DateTime addOneYear(DateTime date) {
    return DateTime(
      date.year + 1,
      date.month,
      date.day,
    );
  }


  // ---------------------------------------------------------
  // الدالة دي مسؤولة عن التأكد إن الفرق بين التطعيمات
  // مش أقل من عدد الأيام المسموح بيها
  //
  // مثال:
  // لو التطعيم الأول يوم 1/10
  // والتطعيم الثاني المفروض يوم 10/10
  // والحد الأدنى 15 يوم
  //
  // الدالة هتأجل التطعيم الثاني لحد ما يبقى
  // الفرق 15 يوم على الأقل.
  // ---------------------------------------------------------
  static DateTime adjustDateForGap(
      DateTime targetDate,

      // قائمة التطعيمات اللي عندنا بالفعل
      List<VaccinationModel> existingList, {

        // عدد الأيام المسموح بيها كحد أدنى بين التطعيمات
        required int gapDays,
      }) {

    // في البداية بنفترض إن التاريخ المطلوب مناسب
    DateTime adjustedDate = targetDate;

    // متغير بنستخدمه علشان نعرف هل التاريخ اتغير ولا لأ
    bool changed;

    // ---------------------------------------------------------
    // بنكرر الفحص لحد ما نضمن إن التاريخ مناسب
    // مع كل التطعيمات الموجودة
    // ---------------------------------------------------------
    do {
      changed = false;

      // بنلف على كل التطعيمات الموجودة
      for (final item in existingList) {

        // بنحسب الفرق بين التاريخ الجديد
        // وتاريخ التطعيم الموجود
        final int difference =
        adjustedDate.difference(item.dueDate).inDays.abs();

        // لو الفرق أقل من الحد الأدنى
        if (difference < gapDays) {

          // بنأجل التاريخ الجديد
          // بحيث يكون بعد التطعيم الموجود بعدد gapDays
          adjustedDate = item.dueDate.add(
            Duration(days: gapDays),
          );

          // بنقول إن التاريخ اتغير
          changed = true;
        }
      }

      // لو التاريخ اتغير، نعيد الفحص مرة تانية
    } while (changed);

    // في النهاية نرجع التاريخ النهائي بعد التعديل
    return adjustedDate;
  }
}